def to_ascii(text):
    """Remove every character that is not plain printable ASCII."""
    if not text:
        return ""
    return re.sub(r'[^\x20-\x7E\n\r\t]', '', text)




def extract_text_from_pdf(file):
    reader = PdfReader(file)
    text = ""
    for page in reader.pages:
        extracted = page.extract_text()
        if extracted:
            text += extracted + "\n"
    return text.strip()




def build_prompt(raw_text, user_info):
    info = (
        "PATIENT INFO:\n"
        "Name: {}\nAge: {}\nGender: {}\n".format(
            user_info.get("name") or "Not specified",
            user_info.get("age") or "Not specified",
            user_info.get("gender") or "Not specified",
        )
    )
    if user_info.get("conditions"):
        info += "Conditions: {}\n".format(user_info["conditions"])
    if user_info.get("medications"):
        info += "Medications: {}\n".format(user_info["medications"])
    return "{}\nREPORT:\n{}\n\nGenerate the structured ReadMed AI report.".format(info, raw_text)





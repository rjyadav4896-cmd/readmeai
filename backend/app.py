def render_pdf(stored):
    # to_ascii called again as final guarantee - belt AND suspenders
    raw_text = to_ascii(stored['text'])
    user_info = stored.get('user_info', {})
    patient  = to_ascii(user_info.get('name', '') or 'N/A')


    pdf  = FPDF(orientation='P', unit='mm', format='A4')
    f    = 'Helvetica'
    pdf.set_auto_page_break(auto=True, margin=22)
    pdf.add_page()


    # Header band
    pdf.set_fill_color(15, 52, 96)
    pdf.rect(0, 0, 210, 44, 'F')
    pdf.set_fill_color(0, 188, 212)
    pdf.rect(0, 44, 210, 3, 'F')


    pdf.set_font(f, 'B', 24)
    pdf.set_text_color(255, 255, 255)
    pdf.set_xy(14, 8)
    pdf.cell(0, 12, 'ReadMed AI', ln=True)


    pdf.set_font(f, '', 10)
    pdf.set_text_color(180, 220, 255)
    pdf.set_xy(14, 23)
    pdf.cell(0, 7, 'Your Medical Report - Simplified', ln=True)


    pdf.set_font(f, '', 9)
    pdf.set_text_color(140, 190, 240)
    pdf.set_xy(14, 33)
    date_str = datetime.now().strftime('%d %B %Y  |  %I:%M %p')
    pdf.cell(0, 7, 'Patient: {}   |   {}'.format(patient, date_str), ln=True)
    pdf.set_y(54)


    # Table state
    in_table      = False
    table_headers = []
    table_rows    = []


    def flush_table():
        nonlocal in_table, table_headers, table_rows
        if not table_headers:
            in_table = False
            return


        nc = len(table_headers)
        W  = 182
        cw = [52, 38, 38, 54] if nc == 4 else ([72, 110] if nc == 2 else [W // nc] * nc)


        # Header row
        pdf.set_fill_color(220, 230, 242)
        pdf.set_text_color(15, 52, 96)
        pdf.set_font(f, 'B', 9)
        pdf.set_x(14)
        for i, h in enumerate(table_headers):
            pdf.cell(cw[i] if i < len(cw) else 40, 8, h[:30], border=1, align='C', fill=True)
        pdf.ln()


        for ri, row in enumerate(table_rows):
            ru = ' '.join(row).upper()
            if 'HIGH' in ru or (' LOW' in ru and 'BELOW' not in ru):
                pdf.set_fill_color(255, 235, 235); pdf.set_text_color(160, 0, 0)
            elif 'MODERATE' in ru or 'BORDERLINE' in ru:
                pdf.set_fill_color(255, 253, 220); pdf.set_text_color(120, 80, 0)
            elif 'NORMAL' in ru:
                pdf.set_fill_color(235, 255, 240); pdf.set_text_color(10, 100, 40)
            elif ri % 2 == 0:
                pdf.set_fill_color(255, 255, 255); pdf.set_text_color(40, 40, 40)
            else:
                pdf.set_fill_color(246, 248, 252); pdf.set_text_color(40, 40, 40)


            pdf.set_font(f, '', 9)
            xs = 14; ys = pdf.get_y(); rh = 7


            for i, cv in enumerate(row):
                if i >= len(cw): continue
                cp = max(1, int(cw[i] / 2.2))
                rh = max(rh, max(1, -(-len(cv.strip()) // cp)) * 6)


            for i, cv in enumerate(row):
                if i >= len(cw): continue
                pdf.set_xy(xs, ys)
                pdf.multi_cell(
                    cw[i],
                    rh / max(1, len(cv.strip()) // max(1, int(cw[i] / 2.2)) + 1),
                    cv.strip(), border=1, align='L', fill=True
                )
                xs += cw[i]


            pdf.set_y(ys + rh)
            pdf.set_text_color(40, 40, 40)


        pdf.ln(4)
        in_table = False; table_headers = []; table_rows = []


    for raw_line in raw_text.split('\n'):
        # Strip backticks, hashes, asterisks, extra spaces
        line = re.sub(r'[`*#]', '', raw_line).strip()


        # Table row
        if '|' in line and line.startswith('|'):
            cells = [to_ascii(c.strip()) for c in line.strip('|').split('|')]
            if all(re.match(r'^[-:]+$', c.replace(' ', '')) for c in cells if c):
                continue
            if not in_table:
                in_table = True; table_headers = cells; table_rows = []
            else:
                if cells: table_rows.append(cells)
            continue
        else:
            if in_table: flush_table()


        if not line:
            pdf.ln(2)
            continue


        # Section header
        section_match = None
        for key, (title, color) in SECTION_MAP.items():
            if line.startswith(key) or key in line[:25]:
                section_match = (title, color)
                break


        if section_match:
            title, (r, g, b) = section_match
            pdf.ln(5)
            pdf.set_fill_color(r, g, b)
            pdf.set_text_color(255, 255, 255)
            pdf.set_font(f, 'B', 12)
            pdf.set_x(14)
            pdf.cell(182, 10, '  ' + title.upper(), ln=True, fill=True)
            # Accent underline
            pdf.set_fill_color(min(r + 30, 255), min(g + 30, 255), min(b + 30, 255))
            pdf.rect(14, pdf.get_y(), 182, 1.5, 'F')
            pdf.ln(4)


        elif line.startswith('---'):
            pdf.set_draw_color(210, 218, 228)
            pdf.set_line_width(0.3)
            pdf.line(14, pdf.get_y(), 196, pdf.get_y())
            pdf.ln(3)


        elif 'disclaimer' in line.lower() or 'informational purposes' in line.lower():
            pdf.ln(3)
            pdf.set_font(f, 'I', 8)
            pdf.set_text_color(130, 130, 140)
            pdf.set_x(14)
            pdf.multi_cell(182, 5, line, align='C')


        elif line.startswith('-'):
            pdf.set_font(f, '', 10)
            pdf.set_text_color(40, 40, 50)
            pdf.set_x(20)
            pdf.multi_cell(176, 6, line, align='L')
            pdf.ln(1)


        else:
            pdf.set_font(f, '', 10)
            pdf.set_text_color(50, 50, 60)
            pdf.set_x(14)
            pdf.multi_cell(182, 6, line, align='L')
            pdf.ln(1)


    if in_table:
        flush_table()


    # Footer
    pdf.set_y(-18)
    pdf.set_fill_color(15, 52, 96)
    pdf.rect(0, pdf.get_y(), 210, 20, 'F')
    pdf.set_font(f, '', 8)
    pdf.set_text_color(160, 200, 240)
    pdf.cell(0, 10,
             'ReadMed AI  |  For informational purposes only  |  Always consult a qualified doctor',
             align='C', ln=True)


    return bytes(pdf.output())




@app.route('/download-report', methods=['GET', 'POST'])
def download_report():
    sid = (
        request.args.get("session_id", "").strip()
        or (request.json or {}).get("session_id", "").strip()
        or request.form.get("session_id", "").strip()
    )
    if not sid or sid not in report_store:
        if report_store:
            sid = list(report_store.keys())[-1]
        else:
            return jsonify({"success": False, "error": "No report found. Generate one first."}), 404


    try:
        pdf_bytes = render_pdf(report_store[sid])
        fname = 'ReadMed_Report_{}.pdf'.format(datetime.now().strftime('%Y%m%d_%H%M'))
        return send_file(io.BytesIO(pdf_bytes), mimetype='application/pdf',
                         as_attachment=True, download_name=fname)
    except Exception as e:
        print("[ERROR] PDF: {}".format(e))
        return jsonify({"success": False, "error": "PDF generation failed: {}".format(e)}), 500





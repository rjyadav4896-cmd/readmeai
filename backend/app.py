@app.route('/process', methods=['POST'])
def process_report():
    raw_text = ""


    if 'file' in request.files and request.files['file'].filename:
        file = request.files['file']
        file.seek(0, 2)
        if file.tell() / (1024 * 1024) > MAX_FILE_SIZE_MB:
            return jsonify({"success": False, "error": "File too large. Max 10MB."}), 413
        file.seek(0)
        if not file.filename.lower().endswith('.pdf'):
            return jsonify({"success": False, "error": "Only PDF files supported."}), 400
        try:
            raw_text = extract_text_from_pdf(file)
        except Exception as e:
            return jsonify({"success": False, "error": "Could not read PDF: {}".format(e)}), 400


    elif request.form.get("manual_text", "").strip():
        raw_text = request.form.get("manual_text", "").strip()


    if not raw_text:
        return jsonify({"success": False, "error": "No report content provided."}), 400


    raw_text = raw_text[:15000]


    user_info = {
        "name":        request.form.get("patient_name", "").strip(),
        "age":         request.form.get("patient_age", "").strip(),
        "gender":      request.form.get("patient_gender", "").strip(),
        "conditions":  request.form.get("known_conditions", "").strip(),
        "medications": request.form.get("medications", "").strip(),
    }


    try:
        result = client.chat.completions.create(
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user",   "content": build_prompt(raw_text, user_info)},
            ],
            model="llama-3.3-70b-versatile",
            temperature=0.3,
            max_tokens=2500,
        )
        # Strip ALL non-ASCII right at the source before storing
        explanation = to_ascii(result.choices[0].message.content)


        session_id = str(uuid.uuid4())
        report_store[session_id] = {
            "text":      explanation,
            "timestamp": datetime.now().isoformat(),
            "user_info": user_info,
        }
        if len(report_store) > 100:
            del report_store[next(iter(report_store))]


        return jsonify({"success": True, "explanation": explanation, "session_id": session_id})


    except Exception as e:
        print("[ERROR] {}".format(e))
        return jsonify({"success": False, "error": "AI processing failed: {}".format(e)}), 500




